"""Resources, disposable source copies and child cleanup for local checks."""
from __future__ import annotations

from contextlib import contextmanager
import os
from pathlib import Path
import shutil
import shlex
import signal
import subprocess
import threading

from check_resources import GIB, resources
_children: set[int] = set()
_lock = threading.Lock()
_cancelled = threading.Event()


# Scheduling estimates, not enforced process limits. Full verification has exceeded 10 GiB.
GROUP_MEMORY_GIB = {'full': 12, 'web': 6, 'quick': 4, 'differential': 3,
                    'tutorials': 3, 'package': 2, 'readings': 3}
MUTANT_MEMORY_BYTES = 6 * GIB


def worker_count(capacity: dict, tasks: int, memory_bytes: int, requested: int | None = None) -> int:
    """Bound runnable independent workers by CPU, memory and the explicit ceiling."""
    ceiling = capacity['cpus'] if requested is None else min(requested, capacity['cpus'])
    return max(1, min(ceiling, tasks, capacity['memory_budget_bytes'] // memory_bytes))


def worker_environment(jobs: int, project: Path | None = None, *,
                       cpu_budget: int | None = None) -> dict[str, str]:
    env = os.environ.copy()
    inherited_budget = int(env.get('HOLD_LEDGER_CPU_BUDGET', resources()['cpus']))
    budget = max(1, min(resources()['cpus'], inherited_budget,
                        cpu_budget if cpu_budget is not None else inherited_budget))
    schedulers = max(1, budget // jobs)
    flags = env.get('ERL_FLAGS', '').strip()
    # Replace only flags generated by this runner; preserve explicit operator flags.
    generated = env.pop('HOLD_LEDGER_AUTO_ERL_FLAGS', '')
    if generated and (flags == generated or flags.endswith(' ' + generated)):
        flags = flags[:-len(generated)].strip()
    tokens = shlex.split(flags)
    automatic = []
    if not any(token == '+S' or (token.startswith('+S') and token[2:3].isdigit())
               for token in tokens):
        automatic += ['+S', f'{schedulers}:{schedulers}']
    if not any(token.startswith('+SDcpu') for token in tokens):
        automatic += ['+SDcpu', '1']
    if not any(token.startswith('+SDio') for token in tokens):
        automatic += ['+SDio', '1']
    generated = ' '.join(automatic)
    env['ERL_FLAGS'] = ' '.join(part for part in (flags, generated) if part)
    env['HOLD_LEDGER_AUTO_ERL_FLAGS'] = generated
    env['HOLD_LEDGER_CPU_BUDGET'] = str(budget)
    env['PYTHONUNBUFFERED'] = '1'
    if project is not None:
        env['HOLD_LEDGER_CACHE_HOME'] = str(project / 'tmp/cache')
        # Workers use the already locked, prepared Python environment.
        env['UV_NO_SYNC'] = '1'
    return env


def source_files(source: Path) -> list[Path]:
    listed = subprocess.check_output(
        ['git', 'ls-files', '-z', '--cached', '--others', '--exclude-standard'], cwd=source)
    paths = [Path(os.fsdecode(name)) for name in listed.split(b'\0') if name]
    # Directory-only Git ignores do not necessarily ignore symlinks. Snapshots
    # link these prepared environments; they are infrastructure, never source.
    return [path for path in paths if path.parts[0] not in ('.local', '.venv')]


def copy_directory(source: Path, destination: Path) -> None:
    if source.is_dir():
        destination.parent.mkdir(parents=True, exist_ok=True)
        # Reflinks where supported; otherwise a real copy, never writable hardlinks.
        subprocess.run(['cp', '-a', '--reflink=auto', str(source), str(destination)], check=True)


def copy_project(source: Path, destination: Path, *, dependencies: bool = True) -> Path:
    subprocess.run(['git', 'clone', '--shared', '--quiet', str(source), str(destination)], check=True)
    # Git clone alone would silently omit uncommitted and untracked source changes.
    for relative in source_files(source):
        src, dst = source / relative, destination / relative
        if not src.exists() and not src.is_symlink():
            if dst.is_file() or dst.is_symlink():
                dst.unlink()
            continue
        dst.parent.mkdir(parents=True, exist_ok=True)
        if dst.is_symlink():
            dst.unlink()
        if src.is_symlink():
            if dst.exists():
                dst.unlink()
            dst.symlink_to(os.readlink(src))
        else:
            shutil.copy2(src, dst)
    if dependencies:
        copy_directory(source / 'deps', destination / 'deps')
        copy_directory(source / 'apps/review_web/deps', destination / 'apps/review_web/deps')
    for name in ('.local', '.venv'):
        if (source / name).is_dir():
            (destination / name).symlink_to((source / name).resolve(), target_is_directory=True)
    return destination


def stop_tree(pid: int) -> None:
    """Include grandchildren that started their own process groups (Lean runners)."""
    parents = {}
    for path in Path('/proc').glob('[0-9]*/stat'):
        try:
            parents[int(path.parent.name)] = int(path.read_text().rsplit(')', 1)[1].split()[1])
        except (OSError, ValueError, IndexError):
            pass
    descendants = {pid}
    while extra := {child for child, parent in parents.items() if parent in descendants} - descendants:
        descendants.update(extra)
    # A process group can survive its leader: kill it even if /proc/<pid> is gone.
    try:
        os.killpg(pid, signal.SIGKILL)
    except ProcessLookupError:
        pass
    for child in descendants:
        try:
            os.kill(child, signal.SIGKILL)
        except ProcessLookupError:
            pass


@contextmanager
def tracked_process(process: subprocess.Popen):
    with _lock:
        _children.add(process.pid)
        cancelled = _cancelled.is_set()
    try:
        if cancelled:
            stop_tree(process.pid)
            raise InterruptedError('Checks cancelled')
        yield process
    except BaseException:
        stop_tree(process.pid)
        process.wait()
        raise
    finally:
        if process.stdout is not None and process.poll() is not None:
            process.stdout.close()
        with _lock:
            _children.discard(process.pid)


@contextmanager
def cancellation_scope():
    _cancelled.clear()
    def cancel(signum, _frame):
        cancel_running()
        raise KeyboardInterrupt(f'Cancelled by signal {signum}')
    previous = {sig: signal.signal(sig, cancel) for sig in (signal.SIGINT, signal.SIGTERM)}
    try:
        yield
    finally:
        for sig, handler in previous.items():
            signal.signal(sig, handler)


def cancel_running() -> None:
    _cancelled.set()
    with _lock:
        children = list(_children)
    for pid in children:
        stop_tree(pid)
