#!/usr/bin/env python3
"""Render CODEOWNERS from the shared review policy; --check rejects drift."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def policy():
    return json.loads((ROOT / 'verification/review-policy.json').read_text())


def codeowners(data):
    owners = ' '.join(data['owners'])
    return '# Generated by scripts/review_policy.py; edit verification/review-policy.json.\n' + ''.join(
        f'{path} {owners}\n' for path in data['tier1_paths'])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    path = ROOT / '.github/CODEOWNERS'
    expected = codeowners(policy())
    if args.check:
        if not path.exists() or path.read_text() != expected:
            parser.exit(1, 'CODEOWNERS differs from review policy; run scripts/review_policy.py\n')
    else:
        path.write_text(expected)


if __name__ == '__main__':
    main()
